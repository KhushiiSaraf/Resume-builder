const pdfParse = require('pdf-parse')
const { generateInterviewReport } = require('../../services/ai.service');
const interviewReportModel = require('../models/interviewReport.model');

/**
 * @description generate interview report using job description and self description or resume 
 */
async function generateInterviewReportController(req, res) {
    try {
        if(!req.body.selfDescription && !req.file){
            return res.status(400).json({ message: "Either self description or resume is required!" })
        }
        let resumeText = "";
        if (req.file) {
            const resumeContent = await pdfParse(req.file.buffer)
            resumeText = resumeContent.text
        }

        const { selfDescription, jobDescription } = req.body;

        const interviewReportByAi = await generateInterviewReport({
            resume: resumeText,
            selfDescription,
            jobDescription
        })

        const interviewReport = await interviewReportModel.create({
            user: req.user._id,
            resume: resumeText,
            selfDescription,
            jobDescription,
            ...interviewReportByAi
        })

        res.status(201).json({
            message: 'Interview report generated successfully',
            interviewReport
        })
    } catch (error) {
        console.error("Error generating interview report:", error);
        res.status(500).json({ message: "Internal server error" });
    }
}

/**
 * @description get interview report by id
 */

async function getInterviewReportByIdController(req, res) {
    try {
        const { interviewId } = req.params;
        const interviewReport = await interviewReportModel.findOne({
            _id: interviewId,
            user: req.user._id
        });

        if (!interviewReport) {
            return res.status(404).json({
                message: "Interview report not found!"
            })
        }

        res.status(200).json({
            message: "Interview report fetched successfully",
            interviewReport
        })
    } catch (error) {
        console.error("Error fetching interview report:", error);
        res.status(500).json({ message: "Internal server error" });
    }
}

/**
 * @description get all interview reports generated by a user
 */

async function getAllInterviewController(req, res) {
    try {
        const interviewReports = await interviewReportModel.find({ user: req.user._id })
            .sort({ createdAt: -1 })
            .select("-resume -jobDescription -selfDescription -skillGaps -technicalQuestions -behavioralQuestions -preparationPlan");

        res.status(200).json({
            message: "Interview reports fetched successfully",
            interviewReports
        })
    } catch (error) {
        console.error("Error fetching interview reports:", error);
        res.status(500).json({ message: "Internal server error" });
    }
}

/**
 * @description delete interview report by id
 */

async function deleteInterviewReportController(req, res) {
    try {
        const { interviewId } = req.params;
        const interviewReport = await interviewReportModel.findOneAndDelete({
            _id: interviewId,
            user: req.user._id
        });

        if (!interviewReport) {
            return res.status(404).json({ message: "Report not found!" })
        }

        res.status(200).json({ message: "Report deleted successfully" })
    } catch (error) {
        console.error("Error deleting report:", error);
        res.status(500).json({ message: "Internal server error" });
    }
}

module.exports = {
    generateInterviewReportController,
    getInterviewReportByIdController,
    getAllInterviewController,
    deleteInterviewReportController
};